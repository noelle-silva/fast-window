// 应用命令分发与全局快捷键、收藏夹动作现场，以及笔记信息更新、仓库恢复、删除分组并关标签
// 三项领域动作（各自成独立子钩子，按依赖顺序在此接线）。
// 状态经 useRepoWorkspaceState 显式入参连接，不引入隐式全局。

